const refused=async markdown=>{
  let cause;
  await withFetch(async()=>answer(markdown),async()=>{try{await fetchWithScrapling(env,'https://company.example/file');}catch(error){cause=error;}});
  return cause;
};

test('a PDF file returned as page text by the Scrapling service is refused, not kept as a read page',async()=>{
  for(const file of [PDF_17,PDF_14]){
    const cause=await refused(file);
    assert.ok(cause,'the file must not come back as a successful read');
    assert.equal(cause.code,'SCRAPLING_BLOCKED_CONTENT');
    assert.equal(cause.failureKind,'blocked_content');
    assert.doesNotMatch(cause.message,/%PDF|obj/,'the refusal must not carry the file content');
  }
});

test('a PDF file is refused even when the service put whitespace or a byte-order mark before its signature',async()=>{
  for(const lead of ['﻿','\n\n ','﻿\n']){
    const cause=await refused(lead+PDF_17);
    assert.equal(cause?.code,'SCRAPLING_BLOCKED_CONTENT',JSON.stringify(lead));
  }
});

test('another binary file returned as page text is refused',async()=>{
  for(const [name,file] of [['zip container',ZIP],['image',IMAGE],['two-byte text',TWO_BYTE],['readable first line',HEADED]]){
    const cause=await refused(file);
    assert.equal(cause?.code,'SCRAPLING_BLOCKED_CONTENT',name);
    assert.equal(cause?.failureKind,'blocked_content',name);
  }
});

test('an ordinary page is still returned: a list of short lines, Danish letters, an icon glyph and a page that mentions the PDF format',async()=>{
  const pages=['Hjem\nOm os\nJob\r\nNyt\n\tSalg\nPris\nKontakt\n'.repeat(30).trim(),PAGE,'Download our product sheet as a PDF. The file starts with the characters %PDF-1.7, which is how a reader recognises it. '+PAGE,PAGE.replace('Kontakt','Kontakt\u0000')];
  for(const page of pages){
    const result=await withFetch(async()=>answer(page),()=>fetchWithScrapling(env,'https://company.example/om'));
    assert.equal(result.data.metadata.source,'scrapling-fallback');
    assert.equal(result.data.markdown,page.trim());
  }
});

