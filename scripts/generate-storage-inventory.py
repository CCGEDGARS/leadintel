"""Build workspace inventory measurements from the installed quota triggers."""
import json
import pathlib
import re
import sqlite3

root = pathlib.Path(__file__).resolve().parents[1]
db = sqlite3.connect(':memory:')
for migration in sorted((root / 'backend/migrations').glob('*.sql')):
    db.executescript(migration.read_text())

models = {}
for table, sql in db.execute("SELECT tbl_name,sql FROM sqlite_master WHERE type='trigger' ORDER BY name"):
    if table == 'workspace_storage_accounts' or not re.search(r'AFTER INSERT ON', sql, re.I) or 'UPDATE workspace_storage_accounts SET' not in sql:
        continue
    sql = re.sub(r'=MAX\(0,(records_bytes|files_bytes)([^;]+?)\) WHERE workspace_id=', r'=\1\2 WHERE workspace_id=', sql, flags=re.I)
    matches = re.findall(r'UPDATE workspace_storage_accounts SET (records_bytes|files_bytes)=\1\+(.+?) WHERE workspace_id=(.+?);', sql, re.S | re.I)
    if not matches:
        raise ValueError('Unrecognized quota trigger: '+sql)
    for meter, expression, scope in matches:
        cols = [r[1] for r in db.execute('pragma table_info('+table+')')]
        name = next((k for k in ('name','company_name','filename','title','full_name','canonical_name','display_name','domain','label') if k in cols), None)
        date = next((k for k in ('updated_at','created_at','saved_at') if k in cols), None)
        model = models.setdefault(table, dict(meter=meter, scope=scope.replace('NEW.', 'r.'), fields=[], name=name, date=date, id='id' if 'id' in cols else None, revision='revision' in cols))
        model['fields'].append(expression.replace('NEW.', 'r.'))
lines = ['// Generated by scripts/generate-storage-inventory.py from the installed quota triggers.','export const storageModels = {']
for table, model in sorted(models.items()):
    lines.append('  '+table+': '+json.dumps(model, separators=(',', ':'))+',')
(root / 'backend/src/workspace-storage-models.js').write_text('\n'.join(lines+['};','']))
