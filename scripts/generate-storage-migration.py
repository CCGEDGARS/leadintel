"""Deterministic logical-byte quota triggers for the complete deployed schema."""
import sqlite3, pathlib
root=pathlib.Path(__file__).resolve().parents[1]
path=root/'backend/migrations/0031_workspace_storage.sql'
c=sqlite3.connect(':memory:')
for p in sorted((root/'backend/migrations').glob('*.sql')):
 if p.name<'0031_': c.executescript(p.read_text())
excluded={'audit_events','oauth_states','workspace_ai_integrations','workspace_service_integrations','workspace_calendly_integrations','gmail_connections','microsoft_mail_connections','workspace_members','enrichment_policies','run_policies','outreach_automation_policies','outreach_contact_suppression','writing_reference_workspaces','writing_reference_slots','writing_reference_jobs','writing_reference_uploads','writing_reference_upload_tickets','intelligence_source_audits','copilot_diagnostics','crm_enrichment_requests','enrichment_requests'}
children={'customer_project_state':('customer_projects','project_id','records'), 'writing_reference_chunks':('writing_reference_sources','source_id','records'),'run_events':('research_runs','run_id','records'),'opportunity_signals':('opportunities','opportunity_id','records'),'customer_brand_asset_chunks':('customer_brand_assets','asset_id','files')}
def scope(t,prefix):
 if t in children:
  parent,key,_=children[t];return f'(SELECT workspace_id FROM {parent} WHERE id={prefix}.{key})'
 return f'{prefix}.workspace_id'
def size(t,prefix):
 if t=='customer_brand_asset_chunks': return f'length({prefix}.chunk_data)'
 if t=='workspace_storage_objects':return f'{prefix}.byte_size'
 cols=[row[1] for row in c.execute('PRAGMA table_info('+t+')') if row[2].upper() in ('TEXT','BLOB') and row[1] not in {'id','workspace_id','user_id','created_by','updated_by','status','state','role','pipeline_stage','lifecycle_status','stop_reason','error_message','error_code','cancel_reason'} and not row[1].endswith(('_id','_at','_until'))]
 return '+'.join(f'COALESCE(length(CAST({prefix}."{col}" AS BLOB)),0)' for col in cols) or '0'
sql=['''-- Generated by scripts/generate-storage-migration.py. Logical content bytes; platform/auth metadata excluded.
CREATE TABLE workspace_storage_accounts(
 workspace_id TEXT PRIMARY KEY REFERENCES workspaces(id) ON DELETE CASCADE,
 records_bytes INTEGER NOT NULL DEFAULT 0 CHECK(records_bytes>=0),
 files_bytes INTEGER NOT NULL DEFAULT 0 CHECK(files_bytes>=0),
 included_records_limit INTEGER NOT NULL DEFAULT 100000000 CHECK(included_records_limit>0),
 included_files_limit INTEGER NOT NULL DEFAULT 1000000000 CHECK(included_files_limit>0),
 plus_records_limit INTEGER NOT NULL DEFAULT 500000000 CHECK(plus_records_limit>=included_records_limit),
 plus_files_limit INTEGER NOT NULL DEFAULT 10000000000 CHECK(plus_files_limit>=included_files_limit),
 plan_key TEXT NOT NULL DEFAULT 'included' CHECK(plan_key IN ('included','plus')),
 paid_until INTEGER NOT NULL DEFAULT 0,
 billing_status TEXT NOT NULL DEFAULT 'not_subscribed',
 stripe_customer_id TEXT UNIQUE,
 stripe_subscription_id TEXT UNIQUE,
 stripe_checkout_id TEXT,
 stripe_checkout_url TEXT,
 stripe_checkout_expires INTEGER NOT NULL DEFAULT 0,
 checkout_token TEXT,
 checkout_lease INTEGER NOT NULL DEFAULT 0,
 billing_event_created INTEGER NOT NULL DEFAULT 0
);
INSERT INTO workspace_storage_accounts(workspace_id) SELECT id FROM workspaces;
CREATE TABLE workspace_storage_objects(
 object_key TEXT PRIMARY KEY,
 workspace_id TEXT NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
 byte_size INTEGER NOT NULL DEFAULT 0 CHECK(byte_size>=0),
 state TEXT NOT NULL DEFAULT 'unmeasured' CHECK(state IN ('unmeasured','ready','writing','deleting')),
 operation_token TEXT,
 lease_until INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX workspace_storage_objects_scope ON workspace_storage_objects(workspace_id,state);
CREATE TABLE workspace_storage_webhook_events(
 event_id TEXT PRIMARY KEY,
 created INTEGER NOT NULL,
 processed_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
INSERT OR IGNORE INTO workspace_storage_objects(object_key,workspace_id)
 SELECT original_key,workspace_id FROM writing_reference_sources WHERE original_key<>'' AND status<>'Deleted';
INSERT OR IGNORE INTO workspace_storage_objects(object_key,workspace_id)
 SELECT text_key,workspace_id FROM writing_reference_sources WHERE text_key<>'' AND status<>'Deleted';
INSERT OR IGNORE INTO workspace_storage_objects(object_key,workspace_id)
 SELECT catalogue_key,workspace_id FROM writing_reference_sources WHERE catalogue_key<>'' AND status<>'Deleted';
INSERT OR IGNORE INTO workspace_storage_objects(object_key,workspace_id)
 SELECT original_key,workspace_id FROM writing_reference_uploads WHERE original_key<>'';
INSERT OR IGNORE INTO workspace_storage_objects(object_key,workspace_id)
 SELECT text_key,workspace_id FROM writing_reference_uploads WHERE text_key<>'';
''']
tables=[]
for (t,) in c.execute("SELECT name FROM sqlite_master WHERE type='table' ORDER BY name").fetchall():
 cols={x[1] for x in c.execute('PRAGMA table_info('+t+')')}
 if t not in excluded and ('workspace_id' in cols or t in children): tables.append((t,children.get(t,(None,None,'records'))[2]))
# Backfill before installing guards: preserve existing over-quota records, and allow reductions thereafter.
for t,category in tables:
 ws=scope(t,'r'); n=size(t,'r');sql.append(f'UPDATE workspace_storage_accounts SET {category}_bytes={category}_bytes+COALESCE((SELECT SUM({n}) FROM {t} r WHERE {ws}=workspace_storage_accounts.workspace_id),0);\n')
tables.append(('workspace_storage_objects','files'))
for t,category in tables:
 nw=scope(t,'NEW');ow=scope(t,'OLD');ns=size(t,'NEW');os=size(t,'OLD');counter=f'{category}_bytes'
 limit=f"CASE WHEN plan_key='plus' AND paid_until>unixepoch() THEN plus_{category}_limit ELSE included_{category}_limit END"
 # Legacy reconciliation must record actual bytes even when already over quota.
 bypass="NEW.state='ready' AND OLD.state='unmeasured'" if t=='workspace_storage_objects' else '0'
 sql.append(f'''CREATE TRIGGER storage_{t}_insert AFTER INSERT ON {t} BEGIN
 INSERT OR IGNORE INTO workspace_storage_accounts(workspace_id) VALUES({nw});
 SELECT CASE WHEN ({ns})>0 AND EXISTS(SELECT 1 FROM workspace_storage_accounts WHERE workspace_id={nw} AND {counter}+({ns})>({limit})) THEN RAISE(ABORT,'WORKSPACE_STORAGE_FULL') END;
 UPDATE workspace_storage_accounts SET {counter}={counter}+({ns}) WHERE workspace_id={nw};
END;
CREATE TRIGGER storage_{t}_update AFTER UPDATE ON {t} BEGIN
 SELECT CASE WHEN {nw} IS NOT {ow} THEN RAISE(ABORT,'WORKSPACE_STORAGE_SCOPE_IMMUTABLE') END;
 SELECT CASE WHEN NOT({bypass}) AND ({ns})>({os}) AND EXISTS(SELECT 1 FROM workspace_storage_accounts WHERE workspace_id={nw} AND {counter}+({ns})-({os})>({limit})) THEN RAISE(ABORT,'WORKSPACE_STORAGE_FULL') END;
 UPDATE workspace_storage_accounts SET {counter}={counter}+({ns})-({os}) WHERE workspace_id={nw};
END;
CREATE TRIGGER storage_{t}_delete AFTER DELETE ON {t} BEGIN
 UPDATE workspace_storage_accounts SET {counter}={counter}-({os}) WHERE workspace_id={ow};
END;
''')
for child,(parent,key,_) in children.items():
 sql.append(f'CREATE TRIGGER storage_{parent}_{child}_cascade BEFORE DELETE ON {parent} BEGIN DELETE FROM {child} WHERE {key}=OLD.id; END;\n')
path.write_text('\n'.join(sql))
print(f'{len(tables)} metered tables, {len(sql)} blocks, {path.stat().st_size} bytes')
